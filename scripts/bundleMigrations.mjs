// Concatenates supabase/migrations/*.sql into supabase/setup.sql, a single script
// that can be pasted into the Supabase SQL Editor for a fresh project.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const migrationsDir = join(import.meta.dirname, "..", "supabase", "migrations");
const outputFile = join(import.meta.dirname, "..", "supabase", "setup.sql");

const files = (await readdir(migrationsDir)).filter((file) => file.endsWith(".sql")).sort();
const parts = await Promise.all(
  files.map(
    async (file) =>
      `-- ===== ${file} =====\n\n${await readFile(join(migrationsDir, file), "utf8")}`,
  ),
);

const header = `-- GENERATED by \`npm run db:bundle\` from supabase/migrations. Do not edit by hand.
-- Paste into Supabase → SQL Editor → Run, once, on a fresh project.

begin;

`;
await writeFile(outputFile, `${header}${parts.join("\n")}\ncommit;\n`);
console.log(`Bundled ${files.length} migration(s) into supabase/setup.sql`);
